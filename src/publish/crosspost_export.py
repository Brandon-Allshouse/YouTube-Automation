"""Crosspost export: package a rendered Short for TikTok and Instagram Reels.

Exports are files for the owner to upload manually (no platform APIs, no automation). Each
platform folder gets: the video (stream-copied when already compliant, re-encoded otherwise), an
SRT caption sidecar built from the scene spec's word timings, and a caption text with the
description, sources link line, hashtags and an AI-voice disclosure line.

``python -m src.publish.crosspost_export --video output/demo/mercator-short.mp4``
``    --spec output/demo/mercator-short.spec.json --script config/demo/mercator_short.yaml``
"""

from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from engine.components.captions import display_word, paginate
from engine.schema.spec import CaptionWord, validate_spec
from src.common import proc
from src.common.ffmpeg import ffmpeg_exe
from src.common.paths import (
    OUTPUT_DIR,
    REPO_ROOT,
    ensure_dir,
    ensure_within,
    safe_join,
    validate_id,
)
from src.production.script import Script, load_script


@dataclass(frozen=True)
class Platform:
    """Export constraints for a platform."""

    name: str
    max_duration_s: float
    max_caption_chars: int
    hashtags: tuple[str, ...]


PLATFORMS = {
    "tiktok": Platform("tiktok", 600.0, 2200, ("#learnontiktok", "#explained")),
    "reels": Platform("reels", 180.0, 2200, ("#explained", "#learn")),
}


def srt_timestamp(t: float) -> str:
    """Seconds → ``HH:MM:SS,mmm``."""
    ms = max(0, round(t * 1000))
    h, ms = divmod(ms, 3_600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def build_srt(words: list[CaptionWord], max_words: int = 6, max_chars: int = 38) -> str:
    """SRT cues from word timings, paginated on speech rhythm like the burned-in captions."""
    lines = []
    for i, page in enumerate(paginate(words, max_words, max_chars, hold=0.4), start=1):
        text = " ".join(display_word(w.w) for w in page.words)
        lines += [str(i), f"{srt_timestamp(page.start)} --> {srt_timestamp(page.end)}", text, ""]
    return "\n".join(lines)


def caption_text(script: Script, platform: Platform) -> str:
    """Post caption: hook title, short description, sources pointer, hashtags, disclosure."""
    parts = [script.titles[0], "", script.description.strip()]
    if script.sources:
        parts += [
            "",
            "Sources: " + "; ".join(sorted({s.url.split("/")[2] for s in script.sources})),
        ]
    if "synthetic voice" not in script.description.lower():
        parts += [
            "",
            "Narration is a synthetic voice; visuals and music are generated by our own code.",
        ]
    parts += ["", " ".join(platform.hashtags)]
    return "\n".join(parts)[: platform.max_caption_chars]


def probe_duration(video: Path) -> float:
    """Duration in seconds via ffmpeg's stderr banner (ffprobe may be absent in venv mode)."""
    res = proc.run([ffmpeg_exe(), "-hide_banner", "-i", str(video)], timeout=60, check=False)
    text = res.stderr.decode(errors="replace")
    import re

    m = re.search(r"Duration: (\d+):(\d+):(\d+\.\d+)", text)
    if not m:
        raise ValueError("could not read video duration")
    h, mi, s = m.groups()
    return int(h) * 3600 + int(mi) * 60 + float(s)


def export(video: Path, spec_path: Path, script: Script, out_root: Path = OUTPUT_DIR / "exports") -> dict[str, Any]:
    """Write per-platform export folders; returns a manifest."""
    video = ensure_within(video, OUTPUT_DIR)
    spec = validate_spec(ensure_within(spec_path, REPO_ROOT).read_text(encoding="utf-8"))
    if spec.format != "short":
        raise ValueError("crosspost export is for 9:16 Shorts")
    duration = probe_duration(video)
    base = ensure_dir(safe_join(out_root, validate_id(script.id, kind="script id")))
    srt = build_srt(list(spec.captions.words))
    manifest: dict[str, Any] = {
        "video": video.name,
        "duration_s": round(duration, 2),
        "platforms": {},
    }
    for name, plat in PLATFORMS.items():
        d = ensure_dir(safe_join(base, name))
        target = d / f"{script.id}-{name}.mp4"
        notes = []
        if duration > plat.max_duration_s:
            notes.append(f"duration {duration:.0f}s exceeds {plat.name} limit {plat.max_duration_s:.0f}s: not exported")
            manifest["platforms"][name] = {"exported": False, "notes": notes}
            continue
        # our masters are already H.264 high / yuv420p / AAC 48 kHz / faststart: stream copy
        proc.run(
            [
                ffmpeg_exe(),
                "-hide_banner",
                "-loglevel",
                "error",
                "-y",
                "-i",
                str(video),
                "-map",
                "0",
                "-c",
                "copy",
                "-movflags",
                "+faststart",
                "-metadata",
                f"title={script.titles[0][:100]}",
                str(target),
            ],
            timeout=300,
        )
        (d / f"{script.id}.srt").write_text(srt, encoding="utf-8")
        (d / "caption.txt").write_text(caption_text(script, plat), encoding="utf-8")
        manifest["platforms"][name] = {
            "exported": True,
            "files": [target.name, f"{script.id}.srt", "caption.txt"],
            "notes": notes,
        }
    (base / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    p = argparse.ArgumentParser(description="Export a Short for TikTok / Reels")
    p.add_argument("--video", type=Path, required=True)
    p.add_argument("--spec", type=Path, required=True)
    p.add_argument("--script", type=Path, required=True)
    a = p.parse_args(argv)
    print(json.dumps(export(a.video, a.spec, load_script(a.script)), indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
