"""Path safety (OWASP path traversal / ASVS V12).

Every file the pipeline writes or reads from a non-constant location goes through these helpers:
paths are resolved and must stay inside an allowed root, and output filenames are generated by us,
never taken from untrusted text.
"""

from __future__ import annotations

import hashlib
import os
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]

DATA_DIR = REPO_ROOT / "data"
OUTPUT_DIR = REPO_ROOT / "output"
LOGS_DIR = REPO_ROOT / "logs"
MODELS_DIR = REPO_ROOT / "models"
ASSETS_DIR = REPO_ROOT / "assets"
CONFIG_DIR = REPO_ROOT / "config"
FIXTURES_DIR = REPO_ROOT / "tests" / "fixtures"

_ID_RE = re.compile(r"^[a-z0-9][a-z0-9_-]{0,63}$")


class UnsafePathError(ValueError):
    """Raised when a path would escape its allowed root or contains forbidden components."""


def ensure_within(path: Path | str, root: Path | str) -> Path:
    """Resolve ``path`` and confirm it lies inside ``root``.

    Args:
        path: Candidate path (absolute or relative to the current directory).
        root: Directory the path must stay within.

    Returns:
        The fully resolved path.

    Raises:
        UnsafePathError: If the resolved path is outside ``root``.
    """
    resolved = Path(path).resolve()
    root_resolved = Path(root).resolve()
    if resolved != root_resolved and root_resolved not in resolved.parents:
        raise UnsafePathError(f"path escapes allowed root: {root_resolved.name}")
    return resolved


def safe_join(root: Path | str, *parts: str) -> Path:
    """Join ``parts`` onto ``root`` and guarantee the result stays inside ``root``.

    Absolute parts, drive letters and ``..`` traversal are rejected rather than normalised away,
    so a hostile value fails loudly.

    Raises:
        UnsafePathError: On absolute components, NUL bytes, or escape from ``root``.
    """
    for part in parts:
        if not part or "\x00" in part:
            raise UnsafePathError("empty or NUL path component")
        if os.path.isabs(part) or re.match(r"^[A-Za-z]:", part):
            raise UnsafePathError("absolute path component")
        if any(seg == ".." for seg in re.split(r"[\\/]", part)):
            raise UnsafePathError("parent traversal component")
    return ensure_within(Path(root).joinpath(*parts), root)


def validate_id(value: str, *, kind: str = "id") -> str:
    """Validate an internal identifier (video/channel/job id) used in paths or filenames.

    Returns:
        ``value`` unchanged if it matches ``[a-z0-9][a-z0-9_-]{0,63}``.

    Raises:
        ValueError: If the identifier is not in the allowed alphabet.
    """
    if not _ID_RE.fullmatch(value):
        raise ValueError(f"invalid {kind}: must match {_ID_RE.pattern}")
    return value


def slug_filename(text: str, *, suffix: str, max_len: int = 40) -> str:
    """Generate a safe filename from arbitrary text: ascii slug + short content hash + suffix.

    The hash keeps names unique even when two texts slug to the same string.
    """
    if not re.fullmatch(r"\.[a-z0-9]{1,8}", suffix):
        raise ValueError("suffix must look like '.mp4'")
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:max_len] or "item"
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()[:8]
    return f"{slug}-{digest}{suffix}"


def ensure_dir(path: Path) -> Path:
    """Create ``path`` (and parents) if missing and return it."""
    path.mkdir(parents=True, exist_ok=True)
    return path
